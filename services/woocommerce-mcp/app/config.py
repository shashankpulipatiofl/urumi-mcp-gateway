"""Configuration for the WooCommerce MCP server.

Every value comes from an environment variable. In Kubernetes those variables are
filled from a ConfigMap (non-secret values) and a Secret (keys and tokens), so no
credential is ever written in source code.
"""

from __future__ import annotations

import os
from dataclasses import dataclass


def _env(name: str, default: str | None = None, *, required: bool = False) -> str:
    value = os.environ.get(name, default)
    if required and not value:
        raise RuntimeError(f"Missing required environment variable: {name}")
    return value or ""


@dataclass(frozen=True)
class Settings:
    # Internal URL of the WordPress Service, e.g. http://urumi-store-wordpress.urumi.svc.cluster.local
    store_url: str
    # WooCommerce REST API key pair (generated by Helm, inserted into WooCommerce by the setup Job)
    consumer_key: str
    consumer_secret: str
    # Shared secret the gateway must send as "Authorization: Bearer <token>". Empty = no auth (dev only).
    mcp_auth_token: str
    # Timezone used to interpret "today" / "yesterday" (must match the store's timezone setting)
    store_timezone: str
    # Seconds to wait for WooCommerce before giving up
    request_timeout: float
    port: int
    store_label: str
    # Public storefront URL (what humans click). Used to fix links WooCommerce generates.
    store_public_url: str = ""

    @classmethod
    def from_env(cls) -> "Settings":
        return cls(
            store_url=_env("WOO_STORE_URL", required=True).rstrip("/"),
            consumer_key=_env("WOO_CONSUMER_KEY", required=True),
            consumer_secret=_env("WOO_CONSUMER_SECRET", required=True),
            mcp_auth_token=_env("MCP_AUTH_TOKEN", ""),
            store_timezone=_env("STORE_TIMEZONE", "UTC"),
            request_timeout=float(_env("WOO_REQUEST_TIMEOUT", "15")),
            port=int(_env("PORT", "8080")),
            store_label=_env("STORE_LABEL", "WooCommerce store"),
            store_public_url=_env("STORE_PUBLIC_URL", "").rstrip("/"),
        )
